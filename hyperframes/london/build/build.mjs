// Generates index.html and compositions/*.html from the shot modules. Run: node build/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import shotsA from "./scenes.mjs";
import shotsB from "./scenes2.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const shots = [...shotsA, ...shotsB];
const only = process.argv[2]; // optional: build only shots whose id starts with this, for quick looks

fs.mkdirSync(path.join(root, "compositions"), { recursive: true });
for (const f of fs.readdirSync(path.join(root, "compositions"))) if (f.endsWith(".html")) fs.unlinkSync(path.join(root, "compositions", f));

let t = 0;
const hosts = [];
for (const s of shots) {
  if (only && !s.id.startsWith(only)) continue;
  fs.writeFileSync(path.join(root, "compositions", `${s.id}.html`), s.html);
  hosts.push(`      <div id="${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${t.toFixed(2)}" data-duration="${s.dur}" data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920"></div>`);
  t += s.dur;
}
const total = Math.round(t * 100) / 100;
if (!only) {
  let a = 0; const starts = {};
  for (const s of shots) { starts[s.id] = Math.round(a * 100) / 100; a += s.dur; }
  fs.writeFileSync(path.join(root, "build", "timing.json"), JSON.stringify({ total, starts }, null, 1));
}

const audio = fs.existsSync(path.join(root, "build", "audio.mjs")) && !only ? (await import("./audio.mjs")).default(shots) : "";

fs.writeFileSync(path.join(root, "index.html"), `<!doctype html>
<html lang="fa" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>London Murders</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1080px; height: 1920px; overflow: hidden; background: #000; }
      #root { position: relative; width: 100%; height: 100%; }
    </style>
  </head>
  <body>
    <!-- Generated by build/build.mjs: edit the shot modules in build/, then run: node build/build.mjs -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1080" data-height="1920">
${hosts.join("\n")}
${audio}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`);
console.log(`${hosts.length} shots, ${total}s`);
let acc = 0;
for (const s of shots) { if (!only || s.id.startsWith(only)) { console.log(`  ${acc.toFixed(1).padStart(5)}s  ${s.id} (${s.dur}s)`); acc += s.dur; } }
